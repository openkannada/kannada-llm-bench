"""Test items, their answer keys, and how each key was checked."""

import json
import random
from collections.abc import Iterable, Sequence
from dataclasses import asdict, dataclass, field, replace
from enum import Enum
from pathlib import Path

LETTERS = "ABCD"


class Check(Enum):
    """Who or what vouches for an item's answer key."""

    HUMAN = "human"
    """Written and checked by the people who made the source dataset."""
    COMPUTED = "computed"
    """Computed by a rule whose output does not depend on Kannada judgment, such as a digit mapping or a
    transliteration standard."""
    NEEDS_READER = "needs-reader"
    """Generated by code that encodes Kannada grammar, which a Kannada reader has not yet checked."""


@dataclass(frozen=True)
class Item:
    id: str
    task: str
    kind: str
    question: str
    answers: tuple[str, ...]
    check: Check
    source: str
    choices: tuple[str, ...] = ()
    passage: str = ""
    meta: dict[str, str] = field(default_factory=dict)

    @property
    def is_choice(self) -> bool:
        return bool(self.choices)

    def to_json(self) -> str:
        data = asdict(self)
        data["check"] = self.check.value
        return json.dumps(data, ensure_ascii=False, sort_keys=True)

    @staticmethod
    def from_json(line: str) -> "Item":
        data = json.loads(line)
        return Item(
            **{
                **data,
                "check": Check(data["check"]),
                "answers": tuple(data["answers"]),
                "choices": tuple(data["choices"]),
            }
        )


def multiple_choice(
    correct: str, distractors: Sequence[str], rng: random.Random
) -> tuple[tuple[str, ...], str]:
    """The 4 options in a random order, and the letter of the correct one."""
    if len(distractors) != 3 or len({correct, *distractors}) != 4:
        raise ValueError(f"need 3 distinct distractors for {correct}: {distractors}")
    options = [correct, *distractors]
    rng.shuffle(options)
    return tuple(options), LETTERS[options.index(correct)]


def balance(items: Sequence[Item]) -> list[Item]:
    """Move each correct option so that within each kind every letter is the answer equally often,
    in an order shuffled with a fixed seed, so that neither always picking 1 letter nor an item's
    position gives the answer away."""
    by_kind: dict[str, list[int]] = {}
    for i, item in enumerate(items):
        if item.is_choice:
            by_kind.setdefault(item.kind, []).append(i)
    target: dict[int, int] = {}
    for kind, positions in by_kind.items():
        letters = [n % len(LETTERS) for n in range(len(positions))]
        random.Random(f"balance-{kind}").shuffle(letters)
        target.update(zip(positions, letters, strict=True))
    out = []
    for i, item in enumerate(items):
        if i not in target:
            out.append(item)
            continue
        current = LETTERS.index(item.answers[0])
        choices = list(item.choices)
        choices[current], choices[target[i]] = choices[target[i]], choices[current]
        out.append(replace(item, choices=tuple(choices), answers=(LETTERS[target[i]],)))
    return out


def write(path: Path, items: Iterable[Item]) -> int:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [item.to_json() for item in items]
    path.write_text("".join(line + "\n" for line in lines), encoding="utf-8")
    return len(lines)


def read(path: Path) -> list[Item]:
    return [Item.from_json(line) for line in path.read_text(encoding="utf-8").splitlines() if line]


def problems(items: Sequence[Item]) -> list[str]:
    """What is wrong with a set of items: duplicate ids, missing answers, or answer letters with no option."""
    found = []
    seen: set[str] = set()
    for item in items:
        if item.id in seen:
            found.append(f"{item.id}: duplicate id")
        seen.add(item.id)
        if not item.answers or not all(item.answers):
            found.append(f"{item.id}: no answer")
        if item.is_choice:
            if len(item.choices) != 4 or len(set(item.choices)) != 4:
                found.append(f"{item.id}: needs 4 distinct options")
            if item.answers not in {(letter,) for letter in LETTERS}:
                found.append(f"{item.id}: answer must be 1 letter")
    return found
